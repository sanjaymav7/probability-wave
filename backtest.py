"""Rolling-window backtest: four forecasters, one synthetic USD/INR history, CRPS for each.

Writes docs/backtest.md and the fan-chart figures.
"""
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from sklearn.ensemble import GradientBoostingRegressor
from pwave import simulate_usdinr, fit_window, shrink, crps_quantiles, forecast_quantiles

W, H, REFIT = 180, 20, 63
LEVELS = np.round(np.arange(0.05, 0.96, 0.05), 2)
sim = simulate_usdinr()
x = sim["x"]
n = len(x)


def pde_quantiles(est):
    return forecast_quantiles(est, H, LEVELS)


def features(t):
    r = np.diff(x)
    seg = x[t - 60:t + 1]
    b, a = np.polyfit(np.arange(61), seg, 1)
    return [x[t] - x[t - 1], x[t] - x[t - 5], x[t] - x[t - 20],
            (x[t] - (a + b * 60)), r[t - 20:t].std(), b]


starts = list(range(W, n - H))
F = {t: features(t) for t in range(60, n)}
history, scores = [], {k: [] for k in ("random walk", "gradient boosting", "PDE", "PDE + EB shrinkage")}
fan = []
gbm = None
for i, T in enumerate(starts):
    y = x[T + H]
    # random walk with the window's realised vol
    r = np.diff(x[T - W:T + 1])
    from scipy.stats import norm
    q_rw = x[T] + r.std() * np.sqrt(H) * norm.ppf(LEVELS)
    scores["random walk"].append(crps_quantiles(q_rw, LEVELS, y))
    # gradient boosting, one model per quantile, refit quarterly on everything already resolved
    if gbm is None or i % REFIT == 0:
        tr = [t for t in range(60, T - H + 1)]
        Xtr = np.array([F[t] for t in tr]); ytr = np.array([x[t + H] - x[t] for t in tr])
        gbm = [GradientBoostingRegressor(loss="quantile", alpha=a, n_estimators=150, max_depth=2,
                                         learning_rate=0.05, random_state=0).fit(Xtr, ytr) for a in LEVELS]
    q_gb = x[T] + np.sort([m.predict([F[T]])[0] for m in gbm])
    scores["gradient boosting"].append(crps_quantiles(q_gb, LEVELS, y))
    # the PDE, raw and shrunk
    est = fit_window(x[:T + 1], W)
    q_pde = pde_quantiles(est)
    scores["PDE"].append(crps_quantiles(q_pde, LEVELS, y))
    q_eb = pde_quantiles(shrink(est, history))
    scores["PDE + EB shrinkage"].append(crps_quantiles(q_eb, LEVELS, y))
    history.append(est)
    fan.append((T + H, q_eb, y))

S = {k: np.array(v) for k, v in scores.items()}
base = S["random walk"].mean()
# paired bootstrap for the shrinkage gain, by 20-day blocks to respect overlap
rng = np.random.default_rng(0)
diff = S["PDE"] - S["PDE + EB shrinkage"]
blocks = np.array_split(diff, len(diff) // H)
boot = [np.concatenate([blocks[j] for j in rng.integers(0, len(blocks), len(blocks))]).mean() for _ in range(2000)]
lo, hi = np.percentile(boot, [2.5, 97.5])

with open("docs/backtest.md", "w") as f:
    f.write(f"# Backtest\n\nGenerated by `python3 backtest.py`. {len(starts):,} rolling windows "
            f"({W}-day fit, {H}-day horizon) over {n // 252} years of synthetic daily USD/INR. "
            f"CRPS on the log-rate, scored on {len(LEVELS)} quantile levels for every model alike. Lower is better.\n\n")
    f.write("| Forecaster | mean CRPS (×1e-3) | vs random walk |\n|:--|--:|--:|\n")
    for k, v in S.items():
        f.write(f"| {k} | {v.mean() * 1e3:.4f} | {100 * (v.mean() / base - 1):+.1f}% |\n")
    f.write(f"\nShrinkage changes PDE CRPS by {100 * (S['PDE + EB shrinkage'].mean() / S['PDE'].mean() - 1):+.2f}% "
            f"(block-bootstrap 95% interval on the gain: [{lo * 1e3:.4f}, {hi * 1e3:.4f}] ×1e-3).\n")
print(open("docs/backtest.md").read())

# fan chart over the last year
tail = fan[-252:]
tt = np.array([a for a, _, _ in tail]); Q = np.array([q for _, q, _ in tail]); Y = np.array([y for _, _, y in tail])
li = lambda l: int(np.argmin(np.abs(LEVELS - l)))
THEMES = {
    "light": dict(bg="#ffffff", fg="#24292f", muted="#8c959f", band="#0969da", y="#cf222e"),
    "dark": dict(bg="#0d1117", fg="#e6edf3", muted="#6e7681", band="#58a6ff", y="#ff7b72"),
}
for name, t in THEMES.items():
    fig, ax = plt.subplots(figsize=(8.06, 3.1), dpi=100)
    fig.patch.set_facecolor(t["bg"]); ax.set_facecolor(t["bg"])
    e = np.exp
    ax.fill_between(tt, e(Q[:, li(.05)]), e(Q[:, li(.95)]), color=t["band"], alpha=.18, lw=0, label="90% band")
    ax.fill_between(tt, e(Q[:, li(.25)]), e(Q[:, li(.75)]), color=t["band"], alpha=.35, lw=0, label="50% band")
    ax.plot(tt, e(Q[:, li(.5)]), color=t["band"], lw=1.2, label="median")
    ax.plot(tt, e(Y), color=t["y"], lw=1.3, label="what happened")
    ax.set_xlabel("trading day", color=t["fg"]); ax.set_ylabel("INR per USD", color=t["fg"])
    ax.tick_params(colors=t["muted"])
    for sp in ax.spines.values():
        sp.set_color(t["muted"])
    ax.spines[["top", "right"]].set_visible(False)
    leg = ax.legend(frameon=False, fontsize=8, ncol=4, loc="upper left")
    for tx in leg.get_texts():
        tx.set_color(t["fg"])
    fig.tight_layout(); fig.savefig(f"docs/fan_{name}.svg", facecolor=t["bg"]); plt.close(fig)
